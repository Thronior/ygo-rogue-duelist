"""Writes docs/i18n/TERMS.md: how every game element is called in each language (from data/i18n/glossary/*.json).

Usage: python tools/i18n/terms_table.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
LANGS = [('de', 'Deutsch'), ('es', 'Español'), ('fr', 'Français'), ('it', 'Italiano'), ('pt', 'Português'),
         ('ja', '日本語'), ('ko', '한국어'), ('zh', '简体中文')]
terms = json.loads((ROOT / 'data/i18n/glossary-terms.json').read_text(encoding='utf8'))
columns = {}
for code, _ in LANGS:
    path = ROOT / f'data/i18n/glossary/{code}.json'
    rows = json.loads(path.read_text(encoding='utf8')) if path.exists() else []
    columns[code] = {r['term']: r['translation'] for r in rows}
cell = lambda s: str(s or '—').replace('|', '\\|').replace('\n', ' ')
lines = ['# Game terms in every language', '',
         'Every translation uses these words for these elements: relic texts, menus, messages and engine prompts alike. '
         'Yu-Gi-Oh rules terms follow the official card texts of each language; game terms (marked GAME in data/i18n/glossary-terms.json) were chosen once and kept.',
         'Generated by `tools/i18n/terms_table.py` from `data/i18n/glossary/*.json`.', '',
         '| English | ' + ' | '.join(name for _, name in LANGS) + ' |', '|' + '---|' * (len(LANGS) + 1)]
for t in terms:
    lines.append('| ' + cell(t['term']) + ' | ' + ' | '.join(cell(columns[code].get(t['term'])) for code, _ in LANGS) + ' |')
out = ROOT / 'docs/i18n/TERMS.md'
out.parent.mkdir(parents=True, exist_ok=True)
out.write_text('\n'.join(lines) + '\n', encoding='utf8')
print('Wrote', out)
