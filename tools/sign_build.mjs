// Signs this build's ID for the official servers (multiplayer/shared/official-build.mjs, 2026-11-24).
//
//   node tools/sign_build.mjs              write android/web/official-build.js: the build ID (VERSION + a hash of the
//                                          game data) and its Ed25519 signature. Without the private key (any fork,
//                                          any other machine) the signature is empty: such builds work with their own
//                                          servers, not the official ones. tools/build_android.py runs this.
//   node tools/sign_build.mjs --new-key    create the key pair once: the private key goes to android/signing/ (git-
//                                          ignored, never published) and the public key is printed for BUILD_PUBLIC_KEY.
//   node tools/sign_build.mjs --verify     check official-build.js against BUILD_PUBLIC_KEY in the rooms Worker's
//                                          wrangler.jsonc; the publisher runs it before uploading a release.
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const KEY=path.join(root,'android/signing/build-signing-key.pem');
const OUT=path.join(root,'android/web/official-build.js');
// The files that make the game what it is: cards, card scripts, engine data and the campaign's Python.
const DATA=['content.json','engine-data.json','scripts.json','campaign-files.json'];

export function buildId(){
 const version=fs.readFileSync(path.join(root,'VERSION'),'utf8').trim();
 const hash=crypto.createHash('sha256');
 for(const name of DATA){const file=path.join(root,'android/web',name);if(fs.existsSync(file)){hash.update(name+'\0');hash.update(fs.readFileSync(file))}}
 return `${version}+${hash.digest('hex').slice(0,16)}`;
}
const publicKeyText=key=>crypto.createPublicKey(key).export({format:'jwk'}).x;
function wranglerKey(){
 const text=fs.readFileSync(path.join(root,'multiplayer/cloudflare/wrangler.jsonc'),'utf8');
 return /"BUILD_PUBLIC_KEY"\s*:\s*"([A-Za-z0-9_-]+)"/.exec(text)?.[1]||'';
}

const arg=process.argv[2];
if(arg==='--new-key'){
 if(fs.existsSync(KEY)){console.error('A build signing key already exists: '+path.relative(root,KEY)+'. Its public key is '+publicKeyText(crypto.createPrivateKey(fs.readFileSync(KEY))));process.exit(1)}
 const {privateKey}=crypto.generateKeyPairSync('ed25519');
 fs.mkdirSync(path.dirname(KEY),{recursive:true});
 fs.writeFileSync(KEY,privateKey.export({type:'pkcs8',format:'pem'}),{mode:0o600});
 console.log('Private key written to '+path.relative(root,KEY)+' (git-ignored; back it up, never publish it).');
 console.log('BUILD_PUBLIC_KEY='+publicKeyText(privateKey));
}else if(arg==='--verify'){
 const source=fs.readFileSync(OUT,'utf8'),id=/id:"([^"]*)"/.exec(source)?.[1],sig=/sig:"([^"]*)"/.exec(source)?.[1];
 const key=wranglerKey();
 if(!key){console.error('No BUILD_PUBLIC_KEY in multiplayer/cloudflare/wrangler.jsonc.');process.exit(1)}
 if(id!==buildId()){console.error(`official-build.js is stale (${id}, expected ${buildId()}). Rebuild.`);process.exit(1)}
 const publicKey=crypto.createPublicKey({key:{kty:'OKP',crv:'Ed25519',x:key},format:'jwk'});
 if(!sig||!crypto.verify(null,Buffer.from(id),publicKey,Buffer.from(sig,'base64url'))){console.error('official-build.js is not signed by the official key: the official servers would refuse this build.');process.exit(1)}
 console.log('Signed build '+id+' OK');
}else{
 const id=buildId();let sig='';
 if(fs.existsSync(KEY))sig=crypto.sign(null,Buffer.from(id),crypto.createPrivateKey(fs.readFileSync(KEY))).toString('base64url');
 const config=JSON.parse(fs.readFileSync(path.join(root,'android/web/multiplayer-config.json'),'utf8'));
 const servers={rooms:config.signalingUrl,replays:config.replaysUrl,stats:config.statsUrl};
 for(const [name,url] of Object.entries(servers))if(!/^https:\/\/[^/?#]+/.test(String(url||'')))throw Error(`multiplayer-config.json: no https address for ${name}`);
 const clean=Object.fromEntries(Object.entries(servers).map(([k,v])=>[k,String(v).replace(/\/+$/,'')]));
 const text=`// Generated by tools/sign_build.mjs from multiplayer-config.json: the servers this build uses, its ID and the ID's\n`+
  `// signature for the official servers. Don't edit; change multiplayer-config.json and rebuild (SELF-HOSTING.md).\n`+
  `// A build without the maintainer's key has an empty signature and works with its own servers.\n`+
  `export const officialBuild={id:"${id}",sig:"${sig}"};\n`+
  `export const servers=${JSON.stringify(clean)};\n`;
 if(!fs.existsSync(OUT)||fs.readFileSync(OUT,'utf8')!==text)fs.writeFileSync(OUT,text);
 console.log(`Build ${id} ${sig?'signed':'unsigned (no build signing key)'}`);
}
